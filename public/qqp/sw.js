// IMPORTANT: bump this version string on EVERY release. The fetch handler below
// serves from cache first, so an already-installed copy keeps serving the old
// app.html forever until this name changes - re-uploading the folder on its own
// reaches nobody who already installed it.
const CACHE_NAME = 'quick-quote-pro-plus-v7';
const ASSETS = [
  './index.html',
  './app.html',
  './manifest.json',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request).then((response) => {
        // don't cache non-GET or cross-origin
        if (event.request.method === 'GET' && response.ok && event.request.url.startsWith(self.location.origin)) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }
        return response;
      }).catch(() => cached);
    })
  );
});
